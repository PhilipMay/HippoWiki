// Writes `src/features/users/common-passwords.ts`, the list of common passwords that new passwords are checked against,
// from a downloaded copy of a SecLists file. The source is pinned to one commit, so that the list can be made again
// exactly as it is. Run it with `npx tsx scripts/common-passwords.ts <downloaded file>`; the file is downloaded from
// SOURCE_URL into a directory outside the repository and is not committed.
//
// The list keeps the entries that meet the length rule of `passwordSchema` (8 to 128, counted as the length of the
// string), lowercased, without duplicates, the first 10,000 in the order of the source (most common first).
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

import { format, resolveConfig } from "prettier";

import { PASSWORD_MAX_LENGTH, PASSWORD_MIN_LENGTH } from "../src/features/users/schema";

const SOURCE_REPOSITORY = "danielmiessler/SecLists";
const SOURCE_COMMIT = "51aa7644c96b3fb6db8de9ecf55aa91195209c80";
const SOURCE_PATH = "Passwords/Common-Credentials/xato-net-10-million-passwords-100000.txt";
const SOURCE_URL = `https://raw.githubusercontent.com/${SOURCE_REPOSITORY}/${SOURCE_COMMIT}/${SOURCE_PATH}`;
const SOURCE_LICENCE = "MIT";

const COUNT = 10_000;
const TARGET = path.join("src", "features", "users", "common-passwords.ts");

/** The entries of the list, in the order of the source. */
function commonPasswords(source: string): string[] {
  const entries = new Set<string>();
  for (const line of source.split(/\r?\n/)) {
    if (line.length < PASSWORD_MIN_LENGTH || line.length > PASSWORD_MAX_LENGTH) continue;
    entries.add(line.toLowerCase());
    if (entries.size === COUNT) break;
  }
  if (entries.size < COUNT) {
    throw new Error(`The source has only ${entries.size} entries that meet the length rule, not ${COUNT}.`);
  }
  return [...entries];
}

/** The content of the generated module. */
function moduleOf(entries: string[]): string {
  return `// Generated by scripts/common-passwords.ts; do not edit. To make it again, download the source file and run
// \`npx tsx scripts/common-passwords.ts <downloaded file>\`.
//
// Source: ${SOURCE_PATH} of ${SOURCE_REPOSITORY}
// at commit ${SOURCE_COMMIT} (${SOURCE_LICENCE} licence),
// ${SOURCE_URL}
//
// The first ${COUNT.toLocaleString("en")} entries of the source, most common first, that are ${PASSWORD_MIN_LENGTH} to ${PASSWORD_MAX_LENGTH} characters long
// (the length of the string, as \`passwordSchema\` counts it), lowercased and without duplicates. No server-only
// imports, like \`schema.ts\`.

/** The common passwords, lowercased. */
export const COMMON_PASSWORDS: readonly string[] = [
${entries.map((entry) => `  ${JSON.stringify(entry)},`).join("\n")}
];

let commonPasswordSet: ReadonlySet<string> | undefined;

/** Whether the password, in any case, is one of the common passwords. */
export function isCommonPassword(password: string): boolean {
  // Built on the first call and not when the module is loaded, so that a bundle that does not call it can drop the list.
  commonPasswordSet ??= new Set(COMMON_PASSWORDS);
  return commonPasswordSet.has(password.toLowerCase());
}
`;
}

async function main(): Promise<void> {
  const file = process.argv[2];
  if (!file) {
    console.error(`Usage: npx tsx scripts/common-passwords.ts <file>, with the file downloaded from ${SOURCE_URL}`);
    process.exitCode = 1;
    return;
  }
  const entries = commonPasswords(readFileSync(file, "utf8"));
  const options = await resolveConfig(TARGET);
  writeFileSync(TARGET, await format(moduleOf(entries), { ...options, filepath: TARGET }));
  console.log(`Wrote ${entries.length} common passwords to ${TARGET}.`);
}

await main();
